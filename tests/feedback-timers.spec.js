import { test, expect } from "./fixtures.js"

test("new request alerts dismiss after eight seconds and feedback after ten seconds", async ({ page }) => {
  await page.goto("/jobseeker/jobs/customer-service")
  await page.getByRole("button", { name: "Request PESO Assistance", exact: true }).click()
  const dialog = page.getByRole("dialog")
  await dialog.getByRole("checkbox").check()
  await page.clock.install()
  await page.clock.pauseAt(new Date(Date.now() + 1000))
  await dialog.getByRole("button", { name: "Submit Request" }).click()
  // Submission paints its pending state with requestAnimationFrame before saving.
  await page.clock.runFor(16)
  await expect(dialog).toContainText("Employment assistance requested")
  const notice = page.getByRole("complementary", { name: "New notification" })
  const feedback = page.locator(".toast-enter")
  await expect(notice).toBeVisible()
  await expect(feedback).toBeVisible()
  await page.mouse.move(0, 0)
  await page.clock.runFor(7999)
  await expect(notice).toBeVisible()
  await page.clock.runFor(1)
  await expect(notice).toHaveCount(0)
  await expect(page.locator(".notice-exit")).toHaveCount(1)
  await expect(feedback).toBeVisible()
  await page.clock.runFor(200)
  await expect(page.locator(".notice-exit")).toHaveCount(0)
  await page.clock.runFor(1800)
  await expect(feedback).toHaveCount(0)
  await expect(page.locator(".toast-exit")).toHaveCount(1)
  await page.clock.runFor(200)
  await expect(page.locator(".toast-exit")).toHaveCount(0)
})
